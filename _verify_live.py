"""Check that the proxied screenshot actually loads, and what the session
embed renders into."""

import json
import re
import urllib.request

POST = "https://dev.to/api/articles/4885250"
PAGE = "https://dev.to/faijaleaqbal/siesta-the-local-agent-that-naps-so-you-dont-have-to-4gfd"


def get(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(request, timeout=90) as response:
        return response.read()


def main() -> int:
    data = json.loads(get(POST).decode("utf-8"))
    body = data.get("body_html", "")

    print("=== the screenshot in the rendered post ===")
    for match in re.findall(r'<img[^>]*>', body):
        if "siesta" in match or "raw.githubusercontent" in match:
            print("  " + match[:300])
            src = re.search(r'src="([^"]+)"', match)
            if src:
                url = src.group(1)
                try:
                    payload = get(url)
                    print(f"  -> image proxy returns {len(payload)} bytes, "
                          f"magic={payload[:8]!r} (PNG = b'\\x89PNG')")
                except Exception as exc:
                    print(f"  -> IMAGE FAILED TO LOAD: {exc}")

    print("\n=== the agent_session embed in the rendered post ===")
    idx = body.find("agent_session")
    if idx != -1:
        print("  " + body[max(0, idx - 400): idx + 400].replace("\n", " ")[:800])
    else:
        print("  (not found)")

    print("\n=== AI disclosure in the page ===")
    html = get(PAGE).decode("utf-8", errors="replace")
    for needle in ("AI disclosure", "disclosure", "Some AI", "some_ai", "generated by", "AI assisted", "ai-assisted"):
        print(f"  contains {needle!r}: {needle.lower() in html.lower()}")
    for match in re.findall(r'[^<>]{0,80}[Dd]isclos[^<>]{0,120}', html)[:4]:
        print("  ..." + match.strip()[:180] + "...")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
