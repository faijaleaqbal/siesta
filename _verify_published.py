"""Verify the published DEV post renders everything it should."""

import json
import re
import urllib.request

URL = "https://dev.to/faijaleaqbal/siesta-the-local-agent-that-naps-so-you-dont-have-to-4gfd"


def main() -> int:
    request = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(request, timeout=60) as response:
        html = response.read().decode("utf-8", errors="replace")
    print(f"fetched {len(html)} bytes from {URL}\n")

    checks = {
        "mermaid diagram": "mermaid" in html,
        "screenshot <img>": "siesta-ui" in html,
        "agent_session embed": "agent_session" in html,
        "github repo link": "github.com/faijaleaqbal/siesta" in html,
        "hf26challenge tag": "hf26challenge" in html,
        "AI disclosure badge": bool(re.search(r"ai[-_ ]?disclos|generated by ai|ai-assisted|some ai", html, re.I)),
        "em dash present": "\u2014" in html,
        "sloth emoji present": "\U0001f9a5" in html,
        "no mojibake": "\u00e2\u20ac" not in html and "\u00f0" not in html,
    }
    for label, ok in checks.items():
        print(f"  {label:<24}: {ok}")

    print("\nimage tags:")
    for match in re.findall(r'<img[^>]*src="([^"]+)"[^>]*>', html)[:4]:
        print("  " + match[:160])

    print("\nagent_session occurrences:")
    for match in re.findall(r'.{70}agent_session.{90}', html)[:4]:
        print("  ..." + match.replace("\n", " ") + "...")

    # The public API gives the cleanest view of the rendered body.
    api_url = "https://dev.to/api/articles/4885250"
    with urllib.request.urlopen(urllib.request.Request(api_url, headers={"User-Agent": "Mozilla/5.0"}), timeout=60) as r:
        data = json.loads(r.read().decode("utf-8"))
    body = data.get("body_html", "")
    print(f"\nbody_html length: {len(body)}")
    for label, ok in {
        "mermaid block": "mermaid" in body,
        "img tag": "<img" in body,
        "agent_session": "agent_session" in body,
    }.items():
        print(f"  {label:<24}: {ok}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
